CREATE DATABASE IF NOT EXISTS perpustakaan_smpit CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE perpustakaan_smpit;

CREATE TABLE IF NOT EXISTS users(
 id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,username VARCHAR(80) UNIQUE NOT NULL,
 password VARCHAR(255) NOT NULL,role ENUM('administrator','pustakawan','anggota') DEFAULT 'anggota',
 status ENUM('aktif','nonaktif') DEFAULT 'aktif',class_name VARCHAR(50),created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL UNIQUE,description VARCHAR(255)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS locations(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL UNIQUE,description VARCHAR(255)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS books(
 id INT AUTO_INCREMENT PRIMARY KEY,code VARCHAR(50) UNIQUE NOT NULL,isbn VARCHAR(30),title VARCHAR(255) NOT NULL,
 author VARCHAR(150),publisher VARCHAR(150),publication_year SMALLINT,category_id INT,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS copies(
 id INT AUTO_INCREMENT PRIMARY KEY,book_id INT NOT NULL,code VARCHAR(80) UNIQUE NOT NULL,location_id INT,
 condition_status ENUM('baik','rusak ringan','rusak berat') DEFAULT 'baik',
 status ENUM('tersedia','dipinjam','rusak','hilang') DEFAULT 'tersedia',
 FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE CASCADE,FOREIGN KEY(location_id) REFERENCES locations(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS barcode_history(
 id INT AUTO_INCREMENT PRIMARY KEY,copy_id INT NOT NULL,old_code VARCHAR(80) NOT NULL,new_code VARCHAR(80) NOT NULL,
 reason VARCHAR(255) NOT NULL,changed_by INT NULL,changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(copy_id) REFERENCES copies(id) ON DELETE CASCADE,FOREIGN KEY(changed_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS loans(
 id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,copy_id INT NOT NULL,loan_date DATE NOT NULL,due_date DATE NOT NULL,
 returned_at DATETIME,late_days INT DEFAULT 0,fine DECIMAL(12,2) DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES users(id),FOREIGN KEY(copy_id) REFERENCES copies(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS visits(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,visit_date DATE NOT NULL,visit_time TIME NOT NULL,FOREIGN KEY(user_id) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_logs(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,login_at DATETIME NOT NULL,FOREIGN KEY(user_id) REFERENCES users(id)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings(`key` VARCHAR(50) PRIMARY KEY,value VARCHAR(100) NOT NULL) ENGINE=InnoDB;
